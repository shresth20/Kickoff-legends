#!/usr/bin/env node
/**
 * Studio sounds → assets/audio/audio.js (window.KL_AUDIO = { name: [data URI, …] }), which the game
 * loads as a plain script so it works from file:// (no XHR). Every name in it replaces the synthesised
 * sound of that name (js/audio/Engine.js) — the game ships fully synthesised, and recordings swap in.
 *
 *   assets/sound/kick_low.mp3          → "kick_low" (one take)
 *   assets/sound/kick_low/*.mp3        → "kick_low" (several takes: one is picked at random each time)
 *   assets/sound/vo/en/comm_goal.0.mp3 → "vo_en_comm_goal.0" (sub-folders join with "_")
 *
 * Names the game asks for: every recipe in js/audio/Sfx.js (kick_low, kick_long, header, crossbar,
 * whistle_kickoff, goal_horn, ui_click …), crowd_murmur / crowd_excited (seamless loops), crowd_roar,
 * crowd_ooh, crowd_aww, crowd_hey, crowd_boo, crowd_applause (loop), crowd_clap, amb_day / amb_night
 * (loops), music_menu / music_victory / music_defeat / music_tension (loops) and vo_<locale>_<key>.<n>
 * for the announcer's lines (locales.json comm_*). Use .mp3 or .m4a: Safari can't decode .ogg.
 *
 *   npm run audio:build
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname, relative, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'assets/sound');
const out = resolve(root, 'assets/audio/audio.js');
const MIME = { '.mp3': 'audio/mpeg', '.m4a': 'audio/mp4', '.aac': 'audio/aac', '.wav': 'audio/wav', '.ogg': 'audio/ogg', '.opus': 'audio/ogg', '.webm': 'audio/webm', '.flac': 'audio/flac' };

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

const samples = {};
let bytes = 0;
if (existsSync(src)) {
  for (const file of walk(src).sort()) {
    const ext = extname(file).toLowerCase();
    if (!MIME[ext]) continue;
    const rel = relative(src, file).split(/[\\/]/);
    rel[rel.length - 1] = rel[rel.length - 1].slice(0, -ext.length);
    // a file inside a folder named after a sound is one take of that sound
    const parent = rel.length > 1 ? rel.slice(0, -1).join('_') : null;
    const own = rel.join('_');
    const name = parent && rel[0] !== 'vo' ? parent : own;
    if (ext === '.ogg' || ext === '.opus') console.warn(`  ${relative(root, file)}: Safari can't decode ${ext} — prefer .mp3 / .m4a`);
    const data = readFileSync(file);
    bytes += data.length;
    (samples[name] ||= []).push(`data:${MIME[ext]};base64,${data.toString('base64')}`);
  }
}

mkdirSync(dirname(out), { recursive: true });
const names = Object.keys(samples);
const banner = `/* GENERATED by tools/make-audio.mjs from assets/sound/ — do not edit by hand.${names.length ? '' : ' Empty: every sound is synthesised.'} */\n`;
writeFileSync(out, `${banner}window.KL_AUDIO = ${JSON.stringify(samples)};\n`);
console.log(`wrote ${relative(root, out)}: ${names.length} sound(s), ${(bytes / 1048576).toFixed(1)} MB${names.length ? ` — ${names.join(', ')}` : ' (everything synthesised)'}`);
if (bytes > 12 * 1048576) console.warn('  that is a lot to load up front: trim the loops, or use a lower bitrate');
