#!/usr/bin/env node
/**
 * Wraps locales/locales.json into locales/locales.js (window.LOCALES = …) so the
 * game can run from file:// without XHR. Run after editing locales.json:
 *   npm run locales:build
 * Also validates that every non-en locale has the same keys as en.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, 'locales/locales.json');
const out = resolve(root, 'locales/locales.js');

const data = JSON.parse(readFileSync(src, 'utf8'));
const enKeys = Object.keys(data.en ?? {});
let problems = 0;
for (const [code, table] of Object.entries(data)) {
  if (code === 'en') continue;
  const missing = enKeys.filter((k) => !(k in table));
  const extra = Object.keys(table).filter((k) => !enKeys.includes(k));
  if (missing.length) console.warn(`[${code}] missing ${missing.length} keys: ${missing.slice(0, 8).join(', ')}${missing.length > 8 ? '…' : ''}`), problems++;
  if (extra.length) console.warn(`[${code}] extra keys not in en: ${extra.join(', ')}`), problems++;
}

const banner = '/* GENERATED by tools/make-locales.mjs from locales.json — do not edit by hand. */\n';
writeFileSync(out, `${banner}window.LOCALES = ${JSON.stringify(data, null, 2)};\n`);
console.log(`wrote ${out} (${Object.keys(data).length} locales, ${enKeys.length} keys)${problems ? ` with ${problems} warning(s)` : ''}`);
